-- Stabilization Pass 2: JobMatch freshness/traceability columns, relational
-- integrity for Application -> ResumeProfile/ResumeVersion, and profile-specific
-- matches that are deleted with their profile.

-- ── Data repair (must run before the foreign keys are added) ─────────────────
-- Before Pass 1 nothing validated these references, so existing rows may point
-- at a deleted profile/version or at one owned by another workspace. Record
-- each removal in the application's history (so no information is lost), then
-- clear the reference. Nothing else about the application changes.
INSERT INTO "application_status_history" ("id", "application_id", "status", "notes", "created_at")
SELECT gen_random_uuid(), a."id", a."status",
       'Integrity repair: removed resume profile reference ' || a."resume_profile_id"::text ||
       ' (profile no longer exists in this workspace).',
       CURRENT_TIMESTAMP
FROM "applications" a
WHERE a."resume_profile_id" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM "resume_profiles" rp
    WHERE rp."id" = a."resume_profile_id" AND rp."organization_id" = a."organization_id"
  );

UPDATE "applications" a
SET "resume_profile_id" = NULL
WHERE a."resume_profile_id" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM "resume_profiles" rp
    WHERE rp."id" = a."resume_profile_id" AND rp."organization_id" = a."organization_id"
  );

INSERT INTO "application_status_history" ("id", "application_id", "status", "notes", "created_at")
SELECT gen_random_uuid(), a."id", a."status",
       'Integrity repair: removed resume version reference ' || a."resume_version_id"::text ||
       ' (version no longer exists in this workspace).',
       CURRENT_TIMESTAMP
FROM "applications" a
WHERE a."resume_version_id" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM "resume_versions" rv
    WHERE rv."id" = a."resume_version_id" AND rv."organization_id" = a."organization_id"
  );

UPDATE "applications" a
SET "resume_version_id" = NULL
WHERE a."resume_version_id" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM "resume_versions" rv
    WHERE rv."id" = a."resume_version_id" AND rv."organization_id" = a."organization_id"
  );

-- Profile-specific matches are a recomputable cache; drop any that reference a
-- resume profile from another workspace.
DELETE FROM "job_matches" jm
WHERE jm."resume_profile_id" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM "resume_profiles" rp
    WHERE rp."id" = jm."resume_profile_id" AND rp."organization_id" = jm."organization_id"
  );

